K = [0xC5610CC0, 0x8E0C628E, 0xA2AFADF7, 0xF2DAD116]
CT = [0x8484AF52, 0x024C302C, 0x3029A370, 0xBAA47C5E]


def f(x, k):
    y = (x ^ k) & M
    return (T[y & 0xFF] ^ T[(y >> 8) & 0xFF] ^ T[(y >> 16) & 0xFF] ^ T[(y >> 24) & 0xFF]) & M


def encrypt_block(l, r):
    for rnd in range(4):
        t = r
        r = (l ^ f(r, K[rnd])) & M
        l = t
    return l, r


def decrypt_block(l, r):
    # invert `t = R; R = L ^ F(R, k); L = t`:
    #   R_old = L_new
    #   L_old = R_new ^ F(L_new, k)
    for rnd in range(3, -1, -1):
        t = l
        l = (r ^ f(l, K[rnd])) & M
        r = t
    return l, r


body = b""
for i in (0, 2):
    l, r = decrypt_block(CT[i], CT[i + 1])
    body += l.to_bytes(4, "big") + r.to_bytes(4, "big")

flag = "COMPFEST18{" + body.decode() + "}"
print(flag)

# re-encrypt and confirm we land back on the stored ciphertext
check = []
for off in (0, 8):
    l = int.from_bytes(body[off:off + 4], "big")
    r = int.from_bytes(body[off + 4:off + 8], "big")
    check.extend(encrypt_block(l, r))
assert check == CT, (check, CT)
print("re-encrypt matches CT:", [hex(v) for v in check])
