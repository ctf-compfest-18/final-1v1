    private static final int[] CT = { 0x8484AF52, 0x024C302C, 0x3029A370, 0xBAA47C5E };

    private static int f(int x, int k) {
        int y = x ^ k;
        return T[y & 0xFF]
             ^ T[(y >>> 8) & 0xFF]
             ^ T[(y >>> 16) & 0xFF]
             ^ T[(y >>> 24) & 0xFF];
    }

    private static int pack(byte[] b, int i) {
        return ((b[i] & 0xFF) << 24)
             | ((b[i + 1] & 0xFF) << 16)
             | ((b[i + 2] & 0xFF) << 8)
             | (b[i + 3] & 0xFF);
    }

    private static int[] encryptBlock(int l, int r) {
        for (int round = 0; round < 4; round++) {
            int t = r;
            r = l ^ f(r, K[round]);
            l = t;
        }
        return new int[] { l, r };
    }

    public static boolean check(String input) {
        if (input.length() != 28) {
            return false;
        }
        if (!input.startsWith("COMPFEST18{") || input.charAt(27) != '}') {
            return false;
        }

        byte[] body = input.substring(11, 27).getBytes(StandardCharsets.US_ASCII);
        int i = 0;
        for (int off = 0; off < 16; off += 8) {
            int[] c = encryptBlock(pack(body, off), pack(body, off + 4));
            if (c[0] != CT[i] || c[1] != CT[i + 1]) {
                return false;
            }
            i += 2;
        }
        return true;
    }

